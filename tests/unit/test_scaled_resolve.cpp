constexpr double kKochOptimum = -109585.73612927811;

Model scaled_ganges() {
  Model model;
  const std::string path =
      (std::filesystem::path(__FILE__).parent_path().parent_path().parent_path() /
       "data/netlib/ganges.mps")
          .string();
  const io::ReadResult read = io::read_model(path, &model);
  EXPECT_TRUE(read.ok) << path << ": " << read.error;
  EXPECT_EQ(model.num_rows(), static_cast<Index>(std::size(kRowExponents)));
  EXPECT_EQ(model.num_cols(), static_cast<Index>(std::size(kColumnExponents)));
  std::vector<double> r;
  std::vector<double> s;
  for (const int e : kRowExponents) r.push_back(std::ldexp(1.0, e));
  for (const int e : kColumnExponents) s.push_back(std::ldexp(1.0, e));
  model.matrix.scale(r, s);
  for (std::size_t j = 0; j < s.size(); ++j) {
    model.col_cost[j] *= s[j];
    model.col_lower[j] /= s[j];
    model.col_upper[j] /= s[j];
  }
  for (std::size_t i = 0; i < r.size(); ++i) {
    model.row_lower[i] *= r[i];
    model.row_upper[i] *= r[i];
  }
  return model;
}

TEST(ScaledResolve, ScaledGangesReachesTheTrueOptimumInScaledSpace) {
  Options options;
  options.set_bool("log_to_console", false);
  // The prescaled retry would also rescue it; this pins the engine-level route.
  options.set_bool("prescale_retry", false);
  const Solution solution = solve(scaled_ganges(), options);
  ASSERT_EQ(solution.status, SolveStatus::kOptimal) << solution.message;
  EXPECT_NEAR(solution.objective, kKochOptimum, 1e-6 * std::fabs(kKochOptimum));
  EXPECT_NE(solution.message.find("tighter tolerances"), std::string::npos) << solution.message;
}

