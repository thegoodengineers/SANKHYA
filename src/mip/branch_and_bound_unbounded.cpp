// SANKHYA - branch and bound: a MILP whose LP relaxation is unbounded (#1343).
//
// The search stops at the root when the relaxation is unbounded, and used to report the MILP
// unbounded on that alone. It is not enough: over integers 2 y - 2 z = 1 has no point at
// all, whatever a column outside the row does to the objective, and the answer to that model
// is infeasible.
//
// With rational data, and every double is rational, a MILP whose relaxation is unbounded is
// unbounded exactly when it has a feasible point (Meyer, "On the existence of optimal
// solutions to integer and mixed-integer programming problems", Mathematical Programming 7,
// 1974): the relaxation's recession cone is then generated by integral directions, and one
// that improves the objective can be followed from the point for ever. So the one thing left
// to find out is whether a point exists, and that is the same search with the objective
// removed. Its relaxation cannot be unbounded, so it ends in one of three ways:
//
//   a point       the MILP is unbounded
//   infeasible    the MILP is infeasible
//   anything else a limit or a numerical failure; that status is reported, with no point
//                 and no bound, because neither verdict was reached
//
// A model with a quadratic objective is left as it was: there the objective can be bounded
// along a ray of the feasible set, and the theorem above is the linear one.

#include <algorithm>
#include <string>
#include <utility>

#include <fmt/format.h>

#include "branch_and_bound_internal.hpp"
#include "core/resource_limits.hpp"
#include "sankhya/mip.hpp"
#include "sankhya/timer.hpp"

namespace sankhya::mip {

Solution solve_branch_and_bound(const Model& given, const Options& requested, Logger& logger,
                                SolveControl* control) {
  const Timer clock;
  Solution answer = search_as_given(given, requested, logger, control);
  if (answer.status != SolveStatus::kUnbounded || given.has_quadratic_objective()) {
    return answer;
  }

  logger.info(
      "The LP relaxation is unbounded; searching for an integer feasible point, which is "
      "what tells an unbounded MILP from an infeasible one (#1343)");
  Model any_point = given;
  std::fill(any_point.col_cost.begin(), any_point.col_cost.end(), 0.0);
  any_point.objective_offset = 0.0;
  Options options = requested;
  const ResourceLimits limits(requested, logger);
  if (limits.has_time_limit()) {
    options.set_double("time_limit", limits.remaining_seconds(clock.elapsed_seconds()));
  }
  // The files are the solve's (as for a sub-MIP, sub_mip_options): this second search is
  // of another objective, so its tree, its progress and its certificate are not the model's.
  for (const char* file : {"checkpoint", "resume", "profile_out", "progress_out",
                           "conflict_out", "debug_solution", "write_certificate"}) {
    options.set_string(file, "");
  }
  Solution found = search_as_given(any_point, options, logger, control);

  const bool has_point =
      (found.status == SolveStatus::kOptimal || found.status == SolveStatus::kFeasible) &&
      !found.col_value.empty();
  if (has_point) {
    answer.message =
        "the LP relaxation is unbounded and the model has an integer feasible point, so the "
        "MILP is unbounded";
    answer.nodes += found.nodes;
    return answer;
  }
  found.nodes += answer.nodes;
  if (found.status == SolveStatus::kInfeasible) {
    found.message = fmt::format(
        "the LP relaxation is unbounded, but the model has no integer feasible point: {}",
        found.message);
    return found;
  }
  // Neither verdict. The bound is the relaxation's, which is unbounded; the zero the second
  // search proved is a bound on nothing the caller asked about.
  found.dual_bound = given.sense == ObjSense::kMaximize ? kInfinity : -kInfinity;
  found.message = fmt::format(
      "the LP relaxation is unbounded, and the search for an integer feasible point, which "
      "would tell unbounded from infeasible, ended without one: {}",
      found.message);
  return found;
}

}  // namespace sankhya::mip
